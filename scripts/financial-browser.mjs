  await page.goto(base + '/login');
  await page.getByLabel('Email institucional').fill('financas@smartcampus.demo');
  await page.getByLabel('Password').fill('Finance123!');
  await page.getByRole('button', { name: 'Entrar no campus' }).click();
  await page.waitForURL('**/ops');
  await page.goto(base + '/financial');
  await page.getByLabel('Nome ou matrícula').fill(student.fullName);
  await page.getByRole('button', { name: 'Pesquisar', exact: true }).click();
  await page.getByRole('button', { name: `Seleccionar ${student.fullName}`, exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Políticas financeiras', exact: true }).count(), 0);
  await page.getByLabel('Descrição', { exact: true }).fill('Propina validada no Core');
  await page.getByLabel('Valor (MZN)', { exact: true }).fill('100');
  await page.getByLabel('Vencimento').fill('2099-01-01T12:00');
